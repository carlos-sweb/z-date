#!/usr/bin/env python3
"""Vendor the system IANA tzdata into src/zones/ and regenerate src/zones.zig.

Usage: python3 scripts/update_tzdata.py [zoneinfo_dir]

- Copies every real TZif file under zoneinfo_dir (default /usr/share/zoneinfo,
  excluding the posix/ and right/ duplicate trees) into src/zones/, preserving
  IANA paths.
- Records symlinked aliases (e.g. US/Pacific -> America/Los_Angeles) without
  duplicating data.
- Generates src/zones.zig: one `pub const <mangled> = @embedFile(...)` per
  canonical zone (so Zig's lazy per-declaration analysis only embeds zones a
  program actually references) plus a `find(name)` runtime lookup whose table
  is only analyzed - and therefore only costs binary size - if called.

Re-run this after an IANA tzdata update and commit the result.
"""

import os
import shutil
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEST = os.path.join(REPO, "src", "zones")
ZIG_OUT = os.path.join(REPO, "src", "zones.zig")

EXCLUDE_TOP = {"posix", "right"}


def is_tzif(path):
    try:
        with open(path, "rb") as f:
            return f.read(4) == b"TZif"
    except OSError:
        return False


def mangle(name):
    """IANA zone name -> valid Zig identifier (must be collision-free)."""
    out = []
    for ch in name.lower():
        if ch == "+":
            out.append("_plus_")
        elif ch in "/-":
            out.append("_")
        else:
            out.append(ch)
    ident = "".join(out)
    # "Etc/GMT-1" and "Etc/GMT+1" must not collide: '-' handled as plain '_'
    # while '+' becomes '_plus_', so gmt_1 vs gmt_plus_1. Verified below.
    return ident


def main():
    canonical = {}  # iana name -> relative path
    aliases = {}  # alias name -> canonical iana name

    for root, dirs, files in os.walk(SRC):
        rel_root = os.path.relpath(root, SRC)
        if rel_root == ".":
            dirs[:] = [d for d in dirs if d not in EXCLUDE_TOP]
        for fname in files:
            full = os.path.join(root, fname)
            rel = os.path.normpath(os.path.join(rel_root, fname)) if rel_root != "." else fname
            if os.path.islink(full):
                target = os.path.realpath(full)
                if not target.startswith(os.path.realpath(SRC)) or not is_tzif(target):
                    continue
                target_rel = os.path.relpath(target, os.path.realpath(SRC))
                if target_rel.split(os.sep)[0] in EXCLUDE_TOP:
                    continue
                aliases[rel] = target_rel
            elif os.path.isfile(full) and is_tzif(full):
                canonical[rel] = rel

    # Aliases must point at canonical zones we actually vendored.
    aliases = {a: t for a, t in aliases.items() if t in canonical and a not in canonical}

    # Collision check on mangled identifiers.
    idents = {}
    for name in sorted(canonical):
        ident = mangle(name)
        if ident in idents:
            raise SystemExit(f"identifier collision: {name} and {idents[ident]} -> {ident}")
        idents[ident] = name

    # Copy files.
    if os.path.isdir(DEST):
        shutil.rmtree(DEST)
    for name in sorted(canonical):
        dst = os.path.join(DEST, name)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copyfile(os.path.join(SRC, name), dst)

    ident_of = {name: ident for ident, name in idents.items()}

    with open(ZIG_OUT, "w") as f:
        f.write(
            "//! Embedded IANA tzdata (TZif files vendored under src/zones/).\n"
            "//! GENERATED by scripts/update_tzdata.py - do not edit by hand.\n"
            "//!\n"
            "//! Each zone is its own `pub const` so Zig's lazy per-declaration\n"
            "//! analysis embeds only the zones a program references. The `find`\n"
            "//! table references every zone, so calling `find` (or anything that\n"
            "//! does, like ZDate.loadEmbeddedTimezone) opts into embedding the\n"
            "//! full database (~1.4 MB).\n\n"
        )
        for name in sorted(canonical):
            f.write(f'pub const {ident_of[name]} = @embedFile("zones/{name}");\n')

        f.write(
            "\nconst Entry = struct { name: []const u8, data: []const u8 };\n\n"
            "/// All zones (canonical names and aliases), sorted by name for\n"
            "/// binary search. Only analyzed - and only embedded - when `find`\n"
            "/// is referenced.\n"
            "const all_zones = [_]Entry{\n"
        )
        rows = [(name, ident_of[name]) for name in canonical]
        rows += [(alias, ident_of[target]) for alias, target in aliases.items()]
        for name, ident in sorted(rows):
            f.write(f'    .{{ .name = "{name}", .data = {ident} }},\n')
        f.write(
            "};\n\n"
            "/// Look up a zone's TZif bytes by IANA name (e.g. \"America/Santiago\").\n"
            "pub fn find(name: []const u8) ?[]const u8 {\n"
            "    var lo: usize = 0;\n"
            "    var hi: usize = all_zones.len;\n"
            "    while (lo < hi) {\n"
            "        const mid = lo + (hi - lo) / 2;\n"
            "        switch (std.mem.order(u8, all_zones[mid].name, name)) {\n"
            "            .lt => lo = mid + 1,\n"
            "            .gt => hi = mid,\n"
            "            .eq => return all_zones[mid].data,\n"
            "        }\n"
            "    }\n"
            "    return null;\n"
            "}\n\n"
            'const std = @import("std");\n'
        )

    print(f"zones: {len(canonical)} canonical + {len(aliases)} aliases -> {ZIG_OUT}")


if __name__ == "__main__":
    main()
