#!/usr/bin/env python3
"""Regenerate src/windows_zones.zig from CLDR's windowsZones.xml.

Usage: python3 scripts/update_windows_zones.py <path/to/windowsZones.xml>

Source of truth: https://raw.githubusercontent.com/unicode-org/cldr/main/common/supplemental/windowsZones.xml
Extracts the territory="001" (world default) mapping for each Windows time
zone key name, which is what GetDynamicTimeZoneInformation reports.
"""

import os
import re
import sys

if len(sys.argv) != 2:
    raise SystemExit(__doc__)

xml_path = sys.argv[1]
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ZIG_OUT = os.path.join(REPO, "src", "windows_zones.zig")

pattern = re.compile(
    r'<mapZone\s+other="([^"]+)"\s+territory="001"\s+type="([^"]+)"'
)

mappings = []
with open(xml_path, encoding="utf-8") as f:
    for line in f:
        m = pattern.search(line)
        if m:
            # `type` can list several IANA zones separated by spaces; the
            # first is the preferred one.
            mappings.append((m.group(1), m.group(2).split()[0]))

mappings.sort()

with open(ZIG_OUT, "w") as f:
    f.write(
        "//! Windows time zone key name -> IANA zone name (CLDR windowsZones\n"
        "//! territory=001 defaults). GENERATED by\n"
        "//! scripts/update_windows_zones.py - do not edit by hand.\n\n"
        "pub const Entry = struct { windows: []const u8, iana: []const u8 };\n\n"
        "/// Sorted by Windows key name (byte order) for binary search.\n"
        "pub const mappings = [_]Entry{\n"
    )
    for windows, iana in mappings:
        f.write(f'    .{{ .windows = "{windows}", .iana = "{iana}" }},\n')
    f.write(
        "};\n\n"
        "/// Map a Windows time zone key name (as reported by\n"
        "/// GetDynamicTimeZoneInformation's TimeZoneKeyName) to its IANA\n"
        "/// equivalent, e.g. \"Pacific Standard Time\" -> \"America/Los_Angeles\".\n"
        "pub fn windowsToIana(windows_name: []const u8) ?[]const u8 {\n"
        "    var lo: usize = 0;\n"
        "    var hi: usize = mappings.len;\n"
        "    while (lo < hi) {\n"
        "        const mid = lo + (hi - lo) / 2;\n"
        "        switch (std.mem.order(u8, mappings[mid].windows, windows_name)) {\n"
        "            .lt => lo = mid + 1,\n"
        "            .gt => hi = mid,\n"
        "            .eq => return mappings[mid].iana,\n"
        "        }\n"
        "    }\n"
        "    return null;\n"
        "}\n\n"
        'const std = @import("std");\n'
    )

print(f"windows zones: {len(mappings)} mappings -> {ZIG_OUT}")
